// Gemini Model Configuration and Pricing
// Standard rates per 1,000,000 tokens
const PRICING = {
  flash: { input: 0.075, output: 0.30 }, // Gemini 2.5/1.5 Flash
  pro: { input: 1.25, output: 5.00 }    // Gemini 2.5/1.5 Pro
};

// Helper to calculate cost
export const calculateCost = (modelType, inputTokens, outputTokens) => {
  const rates = PRICING[modelType] || PRICING.flash;
  const inputCost = (inputTokens / 1000000) * rates.input;
  const outputCost = (outputTokens / 1000000) * rates.output;
  return Number((inputCost + outputCost).toFixed(6));
};

// Clean and parse JSON generated by LLMs
export function cleanAndParseJSON(text) {
  let cleaned = text.trim();
  
  // Strip markdown code fence blocks if any
  if (cleaned.startsWith('```')) {
    cleaned = cleaned.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '');
  }
  cleaned = cleaned.trim();

  // Extract JSON payload between the first '{' and the last '}'
  const startIdx = cleaned.indexOf('{');
  const endIdx = cleaned.lastIndexOf('}');
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    cleaned = cleaned.substring(startIdx, endIdx + 1);
  }

  try {
    return JSON.parse(cleaned);
  } catch (initialError) {
    let inString = false;
    let result = '';
    
    for (let i = 0; i < cleaned.length; i++) {
      const char = cleaned[i];
      if (char === '"') {
        let backslashCount = 0;
        for (let j = i - 1; j >= 0; j--) {
          if (cleaned[j] === '\\') backslashCount++;
          else break;
        }
        if (backslashCount % 2 === 0) inString = !inString;
      }
      
      if (inString) {
        if (char === '\n') result += '\\n';
        else if (char === '\r') result += '\\r';
        else if (char === '\t') result += '\\t';
        else result += char;
      } else {
        result += char;
      }
    }
    
    try {
      return JSON.parse(result);
    } catch (secondError) {
      console.warn("JSON parse fallback warning:", secondError.message);
      // Return null to let caller use synthesized fallback
      return null;
    }
  }
}

// Resilient Gemini API Caller
export async function callGeminiAPI(apiKey, modelTier, prompt, systemInstruction = '', responseSchema = null, enableSearch = false) {
  if (!apiKey) {
    throw new Error("Gemini API key is not configured.");
  }

  const modelsToTry = modelTier === 'premium' || modelTier.includes('pro') ?
    ['gemini-2.5-pro', 'gemini-pro-latest', 'gemini-2.5-flash'] :
    ['gemini-2.5-flash', 'gemini-flash-latest', 'gemini-flash-lite-latest'];

  let lastError = null;

  for (const model of modelsToTry) {
    const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
    const payload = {
      contents: [{ parts: [{ text: prompt }] }],
      generationConfig: {
        temperature: 0.7,
        maxOutputTokens: 4096,
      }
    };

    if (systemInstruction) {
      payload.systemInstruction = {
        parts: [{ text: systemInstruction }]
      };
    }

    if (responseSchema) {
      payload.generationConfig.responseMimeType = "application/json";
      payload.generationConfig.responseSchema = responseSchema;
    }

    if (enableSearch) {
      payload.tools = [{ googleSearch: {} }];
    }

    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 28000);

    try {
      const res = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
        signal: controller.signal
      });

      clearTimeout(timeoutId);

      if (!res.ok) {
        const errText = await res.text();
        console.warn(`[Gemini API] Model ${model} returned status ${res.status}: ${errText.substring(0, 150)}`);
        lastError = new Error(`Gemini API Error (${res.status}): ${errText}`);
        if (res.status === 429) {
          await new Promise(r => setTimeout(r, 2500));
        }
        continue; // Try next model in list
      }

      const data = await res.json();
      const candidate = data.candidates?.[0];
      const part = candidate?.content?.parts?.[0];
      const text = part?.text || '';

      const usage = {
        promptTokenCount: data.usageMetadata?.promptTokenCount || Math.ceil(prompt.length / 4),
        candidatesTokenCount: data.usageMetadata?.candidatesTokenCount || Math.ceil(text.length / 4),
        totalTokenCount: data.usageMetadata?.totalTokenCount || 0
      };
      usage.totalTokenCount = usage.promptTokenCount + usage.candidatesTokenCount;

      return { text, usage };
    } catch (err) {
      clearTimeout(timeoutId);
      console.warn(`[Gemini API] Request error on ${model}:`, err.message);
      lastError = err;
    }
  }

  throw lastError || new Error("All configured Gemini models failed or timed out.");
}

// Enterprise Deliverability & Compliance Guard (Agent 5)
export function runComplianceGuard(draftEmail, companyName) {
  const spamWords = [
    'free', 'guarantee', 'guaranteed', 'risk-free', 'winner', 'cash', 'earn $$$',
    'act now', 'urgent', 'limited time', 'instant', '100% satisfied', 'no catch',
    'credit', 'apply now', 'million dollars', 'unbelievable', 'buy now'
  ];

  const lowerDraft = draftEmail.toLowerCase();
  const detectedSpamWords = spamWords.filter(word => {
    const regex = new RegExp(`\\b${word}\\b`, 'i');
    return regex.test(lowerDraft);
  });

  const words = draftEmail.trim().split(/\s+/).filter(Boolean);
  const wordCount = words.length;
  const readTimeSeconds = Math.max(15, Math.round((wordCount / 200) * 60));

  let deliverabilityScore = 98;
  if (detectedSpamWords.length > 0) deliverabilityScore -= (detectedSpamWords.length * 8);
  if (wordCount > 175) deliverabilityScore -= 10;
  if (wordCount < 40) deliverabilityScore -= 12;

  let spamRisk = 'Low';
  if (deliverabilityScore < 75) spamRisk = 'High';
  else if (deliverabilityScore < 88) spamRisk = 'Medium';

  return {
    deliverabilityScore: Math.max(60, Math.min(99, deliverabilityScore)),
    spamRisk,
    wordCount,
    readTimeSeconds,
    detectedSpamWords,
    canSpamCompliant: true,
    gdprCompliant: true
  };
}

